export type IconName = keyof typeof REGISTRY;

export interface IconProps
  extends Omit<React.ComponentPropsWithoutRef<"svg">, "name" | "strokeWidth"> {
  name: IconName;
  size?: string | number;
  /** Style tier: <2 Linear (idle/menu), 2–2.2 Outline (default controls), >=2.3 Bold (active accents). */
  strokeWidth?: number;
}

function resolveTier(strokeWidth: number): Tier {
  if (strokeWidth < 2) return "linear";
  if (strokeWidth >= 2.3) return "bold";
  return "outline";
}

export function Icon({ name, size = 20, strokeWidth = 2, className, ...props }: IconProps) {
  const Component = REGISTRY[name][resolveTier(strokeWidth)];

  return (
    <Component
      aria-hidden="true"
      size={size}
      strokeWidth={strokeWidth}
      className={className}
      {...props}
    />
  );
}
